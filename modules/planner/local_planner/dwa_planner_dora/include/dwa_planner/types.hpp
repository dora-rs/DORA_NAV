#pragma once

#include <Eigen/Dense>
#include <vector>

namespace dwa_planner {

// =====================================================================
//  二维位姿（从四元数解析后）
// =====================================================================
struct Pose2D {
    double x   = 0.0;
    double y   = 0.0;
    double yaw = 0.0;  // 从四元数转换得到
};

// =====================================================================
//  点云数据（使用Eigen便于后续降采样和过滤）
// =====================================================================
struct PointCloud {
    Eigen::MatrixXf points;  // N×3矩阵 (x, y, z)

    size_t size() const { return points.rows(); }

    void clear() {
        points.resize(0, 3);
    }
};

// =====================================================================
//  速度指令
// =====================================================================
struct Twist {
    double linear_x  = 0.0;
    double angular_z = 0.0;
};

// =====================================================================
//  机器人状态
// =====================================================================
struct RobotState {
    Pose2D pose;
    double vx    = 0.0;  // 当前线速度
    double omega = 0.0;  // 当前角速度
};

} // namespace dwa_planner
